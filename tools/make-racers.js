// Records the racer snails: bots with different skill running each level, saved as a position track (10 samples/s) in racers.js.
// Usage: node tools/make-racers.js   (cosmetic only: racers never touch the sim)
const fs = require('fs'), path = require('path');
const out = {};
const CAST = [
  { n: 'Mossy', c: 0x6bd36b, hold: 10, lift: 0, lat: 150 },
  { n: 'Pip', c: 0x4aa3ff, hold: 20, lift: 0.12, lat: -170 },
  { n: 'Dot', c: 0xb07cff, hold: 30, lift: 0.25, lat: 320 },
];
for (const L of [1, 2, 3, 4]) {
  globalThis.SURF_LEVEL = L;
  const H = require('../verifier/harness.js').load(path.join(__dirname, '..', 'index.html')), mk = () => H();
  const trial = require('../verifier/bot.js')(mk);
  out[L] = [];
  for (const r of CAST) {
    let best = null;
    for (let seed = 1; seed < 40 && !best; seed++) {
      const s = [];
      const res = trial(400, { hold: r.hold, lift: r.lift, seed, init: G => { const r0 = G.ramps[0], rt = G.rightOf(r0.h0); G.pos.x += rt[0] * r.lat; G.pos.z += rt[2] * r.lat; },
        onTick: (G, t) => { if (Math.round(t / 0.01) % 10 === 0) { const c = G.g().contactN || [0, 1, 0]; s.push(Math.round(G.pos.x), Math.round(G.pos.y), Math.round(G.pos.z), Math.round(c[0] * 100), Math.round(c[1] * 100), Math.round(c[2] * 100)); } } });
      if (res.res === 'done' && res.falls === 0) best = { n: r.n, c: r.c, t: res.t, s };
    }
    if (!best) { console.log('L' + L, r.n, 'no clean run'); continue; }
    out[L].push(best); console.log('L' + L, best.n, best.t + 's', best.s.length / 6, 'samples');
  }
}
fs.writeFileSync(path.join(__dirname, '..', 'racers.js'), '// generated by tools/make-racers.js\nglobalThis.RACERS = ' + JSON.stringify(out) + ';\n');
console.log('racers.js', (fs.statSync(path.join(__dirname, '..', 'racers.js')).size / 1024) | 0, 'KB');
